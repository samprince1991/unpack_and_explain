import {
  MIN_POSTED_TO_COMPARE,
  STATUSES,
  rates,
  spokenWords,
  summarize,
  type Idea,
  type IdeaFormat,
  type Taxonomy,
} from "./tracker";

// Renders ideas/README.md: topics first (so new ideas land under an existing theme),
// then schedule, performance, formats, how-to and legend. One function per section.

const pct = (x: number | null | undefined) => (x == null ? "-" : `${(x * 100).toFixed(1)}%`);
const num = (x: number | null | undefined, digits = 0) =>
  x == null ? "-" : x.toLocaleString("en-US", { maximumFractionDigits: digits });
// Table cells can't hold raw pipes.
const cell = (s: string) => s.replace(/\|/g, "\\|");
const byDate = (a: Idea, b: Idea) => a.meta.date.localeCompare(b.meta.date);

const title = (i: Idea) => `[${cell(i.meta.title)}](${i.folder}/idea.md)`;
const status = (i: Idea) => (i.meta.link ? `[${i.meta.status}](${i.meta.link})` : i.meta.status);
const toVerify = (i: Idea) => (i.meta.verify?.length ? String(i.meta.verify.length) : "-");
const longDate = (iso: string) =>
  new Date(`${iso}T00:00:00Z`).toLocaleDateString("en-GB", {
    weekday: "short",
    day: "numeric",
    month: "short",
    timeZone: "UTC",
  });

const header = (ideas: Idea[]) => {
  const counts = STATUSES.map((s) => [s, ideas.filter((i) => i.meta.status === s).length] as const)
    .filter(([, n]) => n > 0)
    .map(([s, n]) => `${n} ${s}`);
  const next = ideas.filter((i) => i.meta.status !== "posted").sort(byDate)[0];
  const nextUp = next ? ` · next up: #${next.meta.id} ${title(next)} (${longDate(next.meta.date)})` : "";
  return `# Ideas

<!-- Generated by \`npm run tracker\` (from video/) out of ideas/*/idea.md and ideas/categories.yml. Edit those files, not this one. -->

Every reel idea for Unpack & Explain, grouped by topic. Check the topics before adding an idea so we build on a theme instead of repeating one.

**${ideas.length} ideas** (by status: ${counts.join(", ")})${nextUp}`;
};

export const renderTopics = (ideas: Idea[], taxonomy: Taxonomy) =>
  taxonomy
    .map(({ category, subcategories }) => {
      const order = (i: Idea) => subcategories.indexOf(i.meta.subcategory);
      const list = ideas
        .filter((i) => i.meta.category === category)
        .sort((a, b) => order(a) - order(b) || byDate(a, b));
      const empty = subcategories.filter((sub) => !list.some((i) => i.meta.subcategory === sub));
      const rows = list.map(
        (i) =>
          `| ${i.meta.subcategory} | ${i.meta.id} | ${title(i)} | ${cell(i.meta.hook)} | ${i.meta.format} | ${status(i)} | ${cell(i.meta.source)} | ${toVerify(i)} |`,
      );
      const table = rows.length
        ? `| Sub-category | # | Idea | Hook | Fmt | Status | Source | To verify |
|---|---|---|---|---|---|---|---|
${rows.join("\n")}`
        : "_No ideas yet._";
      return `### ${category} (${list.length})

${table}${empty.length && rows.length ? `\n\nNo ideas yet: ${empty.join(", ")}.` : ""}`;
    })
    .join("\n\n");

const schedule = (ideas: Idea[], wordsPerSecond: number) => {
  const rows = [...ideas].sort(byDate).map((i) => {
    const words = i.sections.length > 0 ? spokenWords(i) : null;
    return `| ${i.meta.date} | ${i.meta.week} | ${i.meta.id} | ${title(i)} | ${i.meta.category} › ${i.meta.subcategory} | ${i.meta.format} | ${status(i)} | ${num(words)} | ${words == null ? "-" : Math.round(words / wordsPerSecond)} |`;
  });
  return `| Date | Wk | # | Idea | Topic | Fmt | Status | Words | Est. s |
|---|---|---|---|---|---|---|---|---|
${rows.join("\n")}

Est. s assumes ${wordsPerSecond} words/s; the real length comes from the voice-over.`;
};

const performance = (ideas: Idea[]) => {
  const live = ideas.filter((i) => i.meta.status === "posted").sort(byDate);
  if (!live.length) {
    return "Nothing posted yet.";
  }
  const rows = live.map((i) => {
    const m = i.meta.metrics;
    const r = rates(m);
    return `| ${i.meta.id} | ${title(i)} | ${i.meta.link ? `[watch](${i.meta.link})` : "-"} | ${num(m.reach)} | ${m.watch_pct == null ? "-" : `${m.watch_pct}%`} | ${pct(r?.engagement)} | ${pct(r?.shareSave)} | ${num(r?.followsPer1k, 1)} |`;
  });
  return `| # | Idea | Post | Reach | Watch % | Engagement | Share + save | Follows / 1k |
|---|---|---|---|---|---|---|---|
${rows.join("\n")}`;
};

const formats = (ideas: Idea[]) => {
  const s = summarize(ideas);
  const rows = s.byFormat.map(
    (f) =>
      `| ${f.format} | ${f.planned} | ${f.posted} | ${num(f.avgReach)} | ${f.avgWatchPct == null ? "-" : `${f.avgWatchPct.toFixed(1)}%`} | ${pct(f.avgShareSave)} | ${num(f.avgFollowsPer1k, 1)} |`,
  );
  const best = (f: IdeaFormat | null) => f ?? `- (needs ${MIN_POSTED_TO_COMPARE} posted per format)`;
  return `Posted ${s.posted} of ${s.planned} ideas (${s.planned ? Math.round((s.posted / s.planned) * 100) : 0}%).

| Format | Ideas | Posted | Avg reach | Avg watch % | Avg share + save | Avg follows / 1k |
|---|---|---|---|---|---|---|
${rows.join("\n")}

**Best format so far:** by watch time ${best(s.best.watch)}; by share + save rate ${best(s.best.shareSave)}; by follows per 1k reach ${best(s.best.follows)}.

Once about 12-15 ideas are posted, shift the mix toward the format that wins on watch time, shares/saves and follows. Small samples mislead, so formats are only compared once each has at least ${MIN_POSTED_TO_COMPARE} posted.`;
};

const howTo = `**Add an idea**
1. Find its category and sub-category under Topics. If a similar idea exists, give yours a different angle or pick another topic.
2. Copy an \`idea\`-status folder to \`idea-NN-slug/idea.md\` (\`NN\` = next free number) and fill in the front matter: \`category\` and \`subcategory\` exactly as in \`categories.yml\`, plus \`title\`, \`format\`, \`hook\`, \`source\`, \`date\` and \`verify\`.
3. Run \`npm run tracker\` from \`video/\`. It checks every idea and rewrites this page.

**Add a sub-category or category:** add it to \`ideas/categories.yml\` first (the tracker rejects names that aren't listed), then use it in an idea.

**After posting:** set \`status: posted\`, add \`link\` (the live post URL) and fill in \`metrics\`, then run the tracker.

**Names:** once an idea is built it becomes a post, and everything outside \`ideas/\` uses the matching \`post-NN-slug\` name:

| Where | Example |
|---|---|
| Idea, script, caption, link, metrics | \`ideas/idea-02-gps/idea.md\` |
| Video code | \`video/src/posts/post-02-gps/\` |
| Voice-over + captions | \`video/public/posts/post-02-gps/\` |
| Studio composition | \`Post02-Gps\` |
| Renders | \`video/out/post-02-gps.master.mp4\` |`;

const legend = (wordsPerSecond: number) => `- **Formats:** E = pure explainer (saves, shares, authority). F = explainer + failure story (reach, watch time). Q = quick myth / fact (fast to make on busy days).
- **Status:** idea → scripted (script approved) → built (Remotion reel + VO done, now a post) → rendered (master MP4 exported) → posted (\`link\` + metrics filled in). A status with a link opens the live post.
- **To verify:** facts in the idea's \`verify\` list that still need checking before rendering.
- **Words / Est. s:** spoken words in the script (target 100-130) and the length at ${wordsPerSecond} words/s.
- **Metrics:** \`watch_pct\` is average watch time as % of video length. Engagement = (likes + comments + shares + saves) / reach. Share + save = (shares + saves) / reach. Follows / 1k = follows / reach × 1000.
- **Schedule:** dates assume a Monday 2 Nov 2026 start, four reels a week (Mon/Tue/Thu/Fri). Change \`date\` in an idea to move it.`;

export const renderIndex = (ideas: Idea[], taxonomy: Taxonomy, wordsPerSecond: number): string => `${header(ideas)}

## Topics

${renderTopics(ideas, taxonomy)}

## Schedule

${schedule(ideas, wordsPerSecond)}

## Performance

${performance(ideas)}

## Formats

${formats(ideas)}

## How to

${howTo}

## Legend

${legend(wordsPerSecond)}
`;
